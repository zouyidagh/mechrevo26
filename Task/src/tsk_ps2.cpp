extern "C" void ps2_task(void *argument)
{
    TickType_t taskLastWakeTime = xTaskGetTickCount(); // 获取任务开始时间
    ps2_init();
    while(1)
    {
        ps2_update(&rc_ps2);
        vTaskDelayUntil(&taskLastWakeTime, pdMS_TO_TICKS(2)); // 确保任务以定周期2ms运行
    }
}